import { readRules } from "../rules/index.js";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { VERSION } from "../version.js";
import { scan } from "../scan/index.js";
import { architectureMap, architectureMermaid, flowMermaid, flowSteps, type ArchitectureMap } from "../diagrams/architecture.js";
import { dataModel, dataModelMermaid, type DataModel } from "../diagrams/datamodel.js";
import { timeline, timelineMermaid, type Timeline } from "../diagrams/timeline.js";
import { DOC_SPECS, type DocSpec } from "./spec.js";
import type { DocStore } from "./store.js";
import type { Evidence, Item } from "./verify.js";

export const DOCS_DIR = "docs/houserules";
const BEGIN = "<!-- houserules:begin (generated; edit via houserules, not by hand) -->";
const END = "<!-- houserules:end -->";

export interface RenderResult {
  written: string[]; // repo-relative paths
  items: number;
  emptySections: string[];
}

export interface DocDiagrams {
  map: ArchitectureMap;
  model: DataModel;
  history: Timeline;
}

/** Diagrams computed from the code (not from the agent), so they're redrawn on every render. */
export async function computeDiagrams(rootDir: string): Promise<DocDiagrams> {
  const root = path.resolve(rootDir);
  const analysis = await scan(root);
  const map = architectureMap(analysis);
  const [model, history] = await Promise.all([dataModel(root, analysis), timeline(root, map)]);
  return { map, model, history };
}

export async function renderDocs(rootDir: string, store: DocStore, now = new Date(), diagrams?: DocDiagrams): Promise<RenderResult> {
  const root = path.resolve(rootDir);
  const pictures = diagrams ?? (await computeDiagrams(root));
  const written: string[] = [];
  const emptySections: string[] = [];
  let items = 0;
  const date = now.toISOString().slice(0, 10);

  for (const spec of DOC_SPECS) {
    const sections = store.docs[spec.id]?.sections ?? {};
    for (const s of spec.sections) {
      const n = sections[s.id]?.items.length ?? 0;
      items += n;
      if (n === 0 && s.minItems > 0) emptySections.push(`${spec.id}/${s.id}`);
    }
    written.push(await write(root, `${DOCS_DIR}/${spec.file}`, renderDoc(spec, store, date, spec.id === "architecture" ? pictures : undefined)));
  }
  written.push(await write(root, `${DOCS_DIR}/README.md`, renderIndex(store, date)));
  written.push(await writeManaged(root, "AGENTS.md", renderAgents(store, (await readRules(root)).rules)));
  // Claude Code reads CLAUDE.md, and an @-import pulls AGENTS.md in, so both agents share one source.
  written.push(await writeManaged(root, "CLAUDE.md", "@AGENTS.md"));
  return { written, items, emptySections };
}

export function renderDoc(spec: DocSpec, store: DocStore, date: string, diagrams?: DocDiagrams): string {
  const sections = store.docs[spec.id]?.sections ?? {};
  const out: string[] = [
    `# ${spec.title}`,
    "",
    `> ${spec.purpose}`,
    ">",
    `> Generated by houserules ${VERSION} on ${date}. An AI agent wrote these claims from reading the code; every evidence link was then`,
    "> checked automatically (the file, line and name exist). That proves the evidence is real, not that the claim is right, so review it like any doc.",
    "> *(inferred)* marks conclusions drawn from the code rather than read in it; *(ask a maintainer)* marks things only people can answer.",
    "",
  ];
  const filled = spec.sections.filter((s) => sections[s.id]?.items.length);
  if (filled.length > 1) {
    out.push(filled.map((s) => `[${s.title}](#${anchor(s.title)})`).join(" · "), "");
  }
  if (diagrams) out.push(...renderDiagrams(store, diagrams));
  for (const s of filled) {
    out.push(`## ${s.title}`, "");
    for (const item of sections[s.id]!.items) out.push(...renderItem(item, 3, s.id), "");
  }
  if (!filled.length) out.push("_Nothing generated yet. Run houserules in Claude Code or Codex to fill this in._", "");
  return out.join("\n").replace(/\n{3,}/g, "\n\n");
}

const mermaid = (src: string) => ["```mermaid", src, "```", ""];

function renderDiagrams(store: DocStore, d: DocDiagrams): string[] {
  const out = ["## Diagrams", "", "_Drawn from the code on every render, so they stay current. GitHub renders these; other viewers show the source._", ""];
  if (d.map.nodes.length) out.push("### Architecture map", "", "Boxes are folders, arrows are imports (labelled with how many), and rounded nodes are third-party services.", "", ...mermaid(architectureMermaid(d.map)));
  if (d.model.entities.length) {
    // Large models get the most-connected entities so the diagram stays legible.
    const degree = new Map<string, number>();
    for (const r of d.model.relations) for (const n of [r.from, r.to]) degree.set(n, (degree.get(n) ?? 0) + 1);
    const top = [...d.model.entities].sort((a, b) => (degree.get(b.name) ?? 0) - (degree.get(a.name) ?? 0)).slice(0, 20);
    const names = new Set(top.map((e) => e.name));
    const shown = { ...d.model, entities: top, relations: d.model.relations.filter((r) => names.has(r.from) && names.has(r.to)) };
    const note = top.length < d.model.entities.length ? ` Showing the ${top.length} most connected of ${d.model.entities.length}.` : "";
    out.push("### Data model", "", `From the project's ${d.model.source === "typescript" ? "TypeScript domain types" : d.model.source === "sql" ? "SQL schema" : `${d.model.source} definitions`}.${note}`, "", ...mermaid(dataModelMermaid(shown)));
  }
  if (d.history.available && d.history.events.length > 1) out.push("### History", "", ...mermaid(timelineMermaid(d.history, "How the codebase grew")));
  void store;
  return out;
}

function renderItem(item: Item, level: number, section?: string): string[] {
  const badge = item.confidence === "inferred" ? " *(inferred)*" : item.confidence === "needs-human" ? " *(ask a maintainer)*" : "";
  const lines = [`${"#".repeat(level)} ${item.title}${badge}`, ""];
  if (item.body) lines.push(item.body, "");
  if (section === "flows") {
    const steps = flowSteps(item.evidence);
    if (steps.length >= 2) lines.push(...mermaid(flowMermaid(item.title, steps)));
  }
  if (item.evidence.length) lines.push(`<sub>Evidence: ${item.evidence.map(evidenceLink).join(" · ")}</sub>`);
  return lines;
}

/** Links are relative to docs/houserules/, with GitHub-style #L anchors. */
export function evidenceLink(e: Evidence): string {
  const target = `../../${e.path.split("/").map(encodeURIComponent).join("/")}`;
  const lines = e.line ? (e.endLine && e.endLine !== e.line ? `#L${e.line}-L${e.endLine}` : `#L${e.line}`) : "";
  const label = `${e.path}${e.line ? `:${e.line}` : ""}${e.symbol ? ` (${e.symbol})` : ""}`;
  return `[${label}](${target}${lines})${e.note ? ` ${e.note}` : ""}`;
}

function renderIndex(store: DocStore, date: string): string {
  const out = ["# House rules for this repo", "", `Generated by houserules ${VERSION} on ${date}.`, ""];
  for (const spec of DOC_SPECS) {
    const sections = store.docs[spec.id]?.sections ?? {};
    const count = spec.sections.reduce((n, s) => n + (sections[s.id]?.items.length ?? 0), 0);
    out.push(`- **[${spec.title}](./${spec.file})**: ${spec.purpose} (${count} item${count === 1 ? "" : "s"})`);
  }
  out.push("", "These files are regenerated from `.houserules/docs.json`. Change the code or re-run houserules rather than editing them by hand.", "");
  return out.join("\n");
}

/** A short AGENTS.md block: the commands, the rules, and what to reuse, with links into the full docs. */
export function renderAgents(store: DocStore, rules: { title: string; fix?: string; files: string[]; except?: string[] }[] = []): string {
  const arch = store.docs.architecture?.sections ?? {};
  const guide = store.docs.guidelines?.sections ?? {};
  const out: string[] = ["## House rules (houserules)", ""];
  out.push(`Full docs: [${DOCS_DIR}/ARCHITECTURE.md](${DOCS_DIR}/ARCHITECTURE.md), [${DOCS_DIR}/GUIDELINES.md](${DOCS_DIR}/GUIDELINES.md).`, "");

  const running = arch.running?.items ?? [];
  if (running.length) {
    out.push("### Commands", "");
    for (const i of running) out.push(`- **${i.title}**: ${firstLine(i.body)}`);
    out.push("");
  }
  const patterns = guide.patterns?.items ?? [];
  if (patterns.length) {
    out.push("### Follow these patterns", "", "Follow the existing pattern even where the framework docs suggest something else; raise differences instead of \"fixing\" them.", "");
    for (const i of patterns) out.push(`- ${i.title} (e.g. ${evidenceShort(i.evidence[0])})`);
    out.push("");
  }
  const blocks = arch["building-blocks"]?.items ?? [];
  if (blocks.length) {
    out.push("### Reuse before you write", "");
    for (const i of blocks) out.push(`- ${i.title}: ${evidenceShort(i.evidence[0])}`);
    out.push("");
  }
  const tradeoffs = guide.tradeoffs?.items ?? [];
  if (tradeoffs.length) {
    out.push("### Don't \"fix\" these deliberate tradeoffs", "");
    for (const i of tradeoffs) out.push(`- ${i.title}${i.confidence === "inferred" ? " *(inferred)*" : i.confidence === "needs-human" ? " *(ask a maintainer)*" : ""}`);
    out.push("");
  }
  if (rules.length) {
    out.push("### Checked rules", "", "These are enforced on every pull request. Check your changes with the houserules `check_rules` tool (or `houserules ci`) before you finish.", "");
    for (const r of rules) out.push(`- ${r.title}${r.fix ? `: ${r.fix}` : ""} (in \`${r.files.join("`, `")}\`${r.except?.length ? `, not \`${r.except.join("`, `")}\`` : ""})`);
    out.push("");
  }
  out.push("Before exploring the code to answer \"how does X work\", search the team's saved answers (houserules `search_answers`). When you explain something with evidence, offer to save it (`save_answer`).", "");
  out.push("Cite real files when you explain this codebase. If something here looks wrong, say so; it was generated from the code and may be out of date.");
  return out.join("\n");
}

function evidenceShort(e: Evidence | undefined): string {
  if (!e) return "see docs";
  return `\`${e.path}${e.line ? `:${e.line}` : ""}\``;
}

function firstLine(body: string): string {
  const line = body.split("\n").find((l) => l.trim()) ?? "";
  return line.trim();
}

function anchor(title: string): string {
  return title.toLowerCase().replace(/[^a-z0-9 -]/g, "").replace(/ /g, "-");
}

async function write(root: string, rel: string, text: string): Promise<string> {
  const abs = path.join(root, rel);
  await mkdir(path.dirname(abs), { recursive: true });
  await writeFile(abs, text.endsWith("\n") ? text : `${text}\n`);
  return rel;
}

/** Replaces only the houserules block in a file, keeping everything the user wrote around it. */
export async function writeManaged(root: string, rel: string, block: string): Promise<string> {
  const abs = path.join(root, rel);
  let existing = "";
  try {
    existing = await readFile(abs, "utf8");
  } catch {
    // new file
  }
  const managed = `${BEGIN}\n${block.trim()}\n${END}`;
  const start = existing.indexOf(BEGIN);
  const end = existing.indexOf(END);
  let next: string;
  if (start >= 0 && end > start) next = existing.slice(0, start) + managed + existing.slice(end + END.length);
  else if (existing.trim()) next = `${existing.replace(/\s*$/, "")}\n\n${managed}\n`;
  else next = `${managed}\n`;
  if (!next.endsWith("\n")) next += "\n";
  await writeFile(abs, next);
  return rel;
}
